export const isTestDay = (d: DayRecord) =>
  IDS.has(d.id) || TEXTS.has(d.text) || d.song.artist === 'Demo' || (FILLER.has(d.title) && d.text === d.title && !d.song.artist && !d.song.title);

/** Убирает тестовые дни из архива. Возвращает, сколько удалено. */
export async function removeTestDays(): Promise<number> {
  const test = (await store.list()).filter(isTestDay);
  for (const d of test) await store.remove(d);
  return test.length;
}
